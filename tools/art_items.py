def poof():
    """Enemy death: black smoke + red embers, 16x16 x 4."""
    out = []
    specs = [
        (2.0, 3.2, "000000", "ff0000", 5.5),
        (4.0, 2.6, "000000", "ff0000", 7.0),
        (5.5, 2.0, "333941", "c50000", 7.5),
        (6.5, 1.2, "4a5462", "460000", 7.9),
    ]
    for i, (ring, pr, col, ember, er) in enumerate(specs):
        im = blank(16, 16)
        px = im.load()
        centers = [(7.5, 7.5)] if i == 0 else [
            (7.5 + ring * math.cos(math.radians(a)), 7.5 + ring * math.sin(math.radians(a)))
            for a in range(-90, 270, 72)]
        for y in range(16):
            for x in range(16):
                for (cx, cy) in centers:
                    if (x + 0.5 - cx) ** 2 + (y + 0.5 - cy) ** 2 <= pr * pr:
                        px[x, y] = rgba(col)
        for a in range(-54, 306, 72):
            ex = int(7.5 + er * math.cos(math.radians(a)))
            ey = int(7.5 + er * math.sin(math.radians(a)))
            if 0 <= ex < 16 and 0 <= ey < 16:
                px[ex, ey] = rgba(ember)
        if i == 0:
            px[7, 7] = rgba("ff0000")
            px[8, 7] = rgba("ffe3e3")
        out.append(im)
    return out


