CELL_W, CELL_H = 8, 10
ORDER = [chr(c) for c in range(32, 127)] + ["Æ", "Ø", "Å", "æ", "ø", "å", "♥"]


def glyph_image(ch, color="ffffff"):
    top, rows = GLYPHS[ch]
    rows = [r for r in rows.split("/") if r != "" or ch == " "]
    im = blank(CELL_W, CELL_H)
    px = im.load()
    for y, row in enumerate(rows):
        for x, c in enumerate(row):
            if c == "#":
                px[x, top + y] = rgba(color)
    width = max(len(r) for r in rows)
    return im, width


def font_sheet():
    cols = 16
    ims, widths = [], {}
    for ch in ORDER:
        im, w = glyph_image(ch)
        ims.append(im)
        widths[ch] = w
    return sheet(ims, cols), widths


def draw_text(dst, x, y, text, color="ffffff", shadow=None, spacing=1):
    cx = x
    for ch in text:
        if ch == "\n":
            cx = x
            y += CELL_H + 1
            continue
        im, w = glyph_image(ch, color)
        if shadow:
            sh, _ = glyph_image(ch, shadow)
            over(dst, sh, cx + 1, y + 1)
        over(dst, im, cx, y)
        cx += w + spacing
    return cx


def text_width(text, spacing=1):
    return sum(glyph_image(c)[1] + spacing for c in text) - spacing


