# --- weapon: Glodende Sverd remapped to the master palette -----------------
SWORD_REMAP = {"4f4f4f": "4a5462", "7f7f7f": "6d758d", "212121": "141013", "363636": "333941",
               "2b0507": "2b0000", "460000": "460000", "ed1c24": "c50000", "ff0000": "ff0000"}


def sword_orientations(sword_frames):
    """8 frames: [up-right, up-left, down-right, down-left] x [glow off, glow on]."""
    out = []
    for f in sword_frames:
        f = recolor(f, SWORD_REMAP)
        out.append([f, flip_h(f), flip_v(f), flip_h(flip_v(f))])
    return [o for pair in zip(*out) for o in pair]


def slash_arcs():
    """24x24 crescent smears, rows = down, up, left, right; 3 frames each."""
    size, c = 24, 11.5
    spans = [(-100, -30), (-100, 70), (0, 90)]  # degrees, 0 = facing direction, + = clockwise

    def frame(i):
        a0, a1 = spans[i]
        im = blank(size, size)
        px = im.load()
        for y in range(size):
            for x in range(size):
                dx, dy = x + 0.5 - c, y + 0.5 - c
                r = math.hypot(dx, dy)
                ang = math.degrees(math.atan2(dy, dx))
                if not (a0 <= ang <= a1) or not (5.5 <= r <= 11.5):
                    continue
                t = (ang - a0) / (a1 - a0)  # 0 = trailing end, 1 = leading edge
                if i == 2:
                    t *= 0.6
                if r > 10.5:
                    col = "ffe3e3" if t > 0.55 else ("ff0000" if t > 0.25 else "460000")
                elif r > 8.5:
                    col = "ff0000" if t > 0.35 else ("c50000" if t > 0.15 else "2b0000")
                elif r > 7:
                    col = "c50000" if t > 0.3 else "460000"
                else:
                    if t < 0.5:
                        continue
                    col = "460000"
                px[x, y] = rgba(col)
        return im

    right = [frame(i) for i in range(3)]
    left = [flip_h(f) for f in right]
    up = [rot90(f, 1) for f in right]
    down = [rot90(f, 3) for f in right]
    return down + up + left + right


