def dialog_box_9slice():
    """24x24 source; slice at 8px. Right/bottom edges mirrored from left/top."""
    im = BOX.copy()
    left = im.crop((0, 0, 12, 24))
    im.paste(flip_h(left), (12, 0))
    top = im.crop((0, 0, 24, 12))
    im.paste(flip_v(top), (0, 12))
    return im


def nine_slice(src, w, h, s=8):
    out = blank(w, h)
    sw, sh = src.size
    parts = {}
    for j, (y0, y1) in enumerate(((0, s), (s, sh - s), (sh - s, sh))):
        for i, (x0, x1) in enumerate(((0, s), (s, sw - s), (sw - s, sw))):
            parts[(i, j)] = src.crop((x0, y0, x1, y1))
    xs = [(0, s), (s, w - s), (w - s, w)]
    ys = [(0, s), (s, h - s), (h - s, h)]
    for j, (y0, y1) in enumerate(ys):
        for i, (x0, x1) in enumerate(xs):
            p = parts[(i, j)]
            for yy in range(y0, y1, p.height):
                for xx in range(x0, x1, p.width):
                    piece = p.crop((0, 0, min(p.width, x1 - xx), min(p.height, y1 - yy)))
                    out.alpha_composite(piece, (xx, yy))
    return out


