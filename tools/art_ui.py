def logo():
    """'GUSEN' title logo: 2x font, black letters with a red glow and Gusen eyes."""
    text = blank(64, 20)
    x = 1
    for ch in "GUSEN":
        g, w = glyph_image(ch, "000000")
        g = scale(g.crop((0, 1, w, 8)), 2)
        over(text, g, x, 3)
        x += w * 2 + 2
    im = outline(text, "ff0000", diagonal=False)
    im = outline(im, "460000", diagonal=True)
    px = im.load()
    # eyes in the G and the U
    for (ex, ey) in [(4, 9), (7, 9), (16, 12), (19, 12)]:
        px[ex, ey] = rgba("ffffff")
    return im.crop((0, 0, x + 1, 20))
