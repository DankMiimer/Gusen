def shadow():
    """Drop shadow. The only sprite with partial alpha (GBA blend layer)."""
    im = blank(10, 4)
    px = im.load()
    for y in range(4):
        for x in range(10):
            if ((x + 0.5 - 5) / 5) ** 2 + ((y + 0.5 - 2) / 2) ** 2 <= 1:
                px[x, y] = (0, 0, 0, 96)
    return im


